export function getCardById(id: string): CardDefinition | undefined {
  return CARD_DATABASE.find((c) => c.id === id);
}

export function getEarnRate(card: CardDefinition, category: string): number {
  const specific = card.earn_rates.find((r) => r.category === category);
  if (specific) return specific.rate;
  const def = card.earn_rates.find((r) => r.category === 'default');
  return def?.rate ?? 0;
}
